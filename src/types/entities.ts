/** One approve/return decision; the array is the full review history. */
export interface LessonPlanReview {
  id?: string;
  reviewerId: string;
  reviewerName: string;
  decision: 'approved' | 'returned';
  comment?: string | null;
  reviewedAt: string;
}

export interface LessonPlanAttachment {
  key: string;
  filename: string;
  mimeType: string;
  sizeBytes: number;
  uploadedAt: string;
}

/**
 * A week's plan for one lesson.
 *
 * `weekStartDate`, `weekEndDate` and `dueDate` are all derived by the API —
 * the week is snapped to its Monday and the deadline comes from school policy,
 * so none of the three is ever sent by the client. That is what makes `isLate`
 * mean something and what lets the compliance matrix match a plan to a cell by
 * exact date.
 */
export interface LessonPlan extends BaseDocument {
  teacherId: Ref<Teacher>;
  subjectId: Ref<Subject>;
  classroomId: Ref<Classroom>;
  semesterId: Ref<Semester>;
  title: string;
  description?: string | null;
  weekStartDate: string;
  weekEndDate: string;
  activities: LessonActivity[];
  attachments: LessonPlanAttachment[];
  status: LessonPlanStatus;
  dueDate: string;
  submittedAt?: string | null;
  /** Fixed at submission — a later policy change cannot rewrite it. */
  isLate: boolean;
  reviews: LessonPlanReview[];
  lastReviewedAt?: string | null;
}


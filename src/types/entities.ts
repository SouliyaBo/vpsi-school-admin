// ── Attendance ──────────────────────────────────────────────────────────────

/**
 * One student's presence on one day, or in one period of it.
 *
 * `period` is `0` for whole-day roll call and `1..n` for a per-period one; it is
 * part of the API's uniqueness key, so a school may use either model or both.
 * The list endpoint populates student, classroom and subject; the roll-call
 * sheet and the summaries return their own flattened shapes instead.
 */
export interface Attendance extends BaseDocument {
  studentId: Ref<Student>;
  /** The timetabled lesson this roll call belongs to. */
  teachingAssignmentId: Ref<TeachingAssignment>;
  classroomId: Ref<Classroom>;
  semesterId: Ref<Semester>;
  schoolYearId: Ref<SchoolYear>;
  date: string;
  period: number;
  subjectId: Ref<Subject>;
  /** The teacher whose lesson it was, per the timetable. */
  teacherId: Ref<Teacher>;
  status: AttendanceStatus;
  /** Only meaningful when `status` is `late`. */
  minutesLate?: number | null;
  reason?: string | null;
  /** Whoever submitted it, which is not always `teacherId`. */
  recordedBy: Ref<User>;
}

// ── Behavior log ────────────────────────────────────────────────────────────

/**
 * One student's line in the homeroom behaviour register.
 *
 * The paper form's row mixes two levels — a note about the class, and named
 * students with what each did — and is stored one record per student so a
 * student's own history is a direct lookup. `groupId` is what puts a row back
 * together: several records written in one entry share it, and it is the id the
 * write endpoints take.
 *
 * `studentId` is null on a row that only records the state of the class, which
 * the paper form allows and homeroom teachers use constantly.
 */
export interface BehaviorLog extends BaseDocument {
  groupId: string;
  studentId?: Ref<Student> | null;
  /** The timetabled lesson the observation was made in. */
  teachingAssignmentId: Ref<TeachingAssignment>;
  classroomId: Ref<Classroom>;
  semesterId: Ref<Semester>;
  schoolYearId: Ref<SchoolYear>;
  date: string;
  period: number;
  subjectId: Ref<Subject>;
  /** The teacher whose lesson it was, per the timetable. */
  teacherId: Ref<Teacher>;
  /** ສະພາບລວມພາຍໃນຫ້ອງ — the class as a whole. */
  classNote?: string | null;
  /** ພຶດຕິກຳ(ລາຍບຸກຄົນ) — what this student did. */
  behavior?: string | null;
  /** ຕັດຄະແນນ/ຕັກເຕືອນ — free text, as written on the paper form. */
  action?: string | null;
  remark?: string | null;
  /** Whoever filed it, which is not always `teacherId`. */
  recordedBy: Ref<User>;
}

// ── Teaching assignments ────────────────────────────────────────────────────

/**
 * One weekly period.
 *
 * Times are local wall-clock `"HH:mm"` with no date or timezone part, so they
 * compare lexicographically in chronological order — which is what both the
 * API's overlap check and the timetable sorting rely on.
 */
export interface SchedulePeriod {
  /** 0 = Sunday … 6 = Saturday, matching `Date#getDay()`. */
  dayOfWeek: number;
  startTime: string;
  endTime: string;
  /** Physical room. When set, the API also checks it for double-booking. */
  room?: string | null;
  periodNumber?: number | null;
  /**
   * A slot two teachers take turns in.
   *
   * The school runs some periods as a swap — one teacher takes ມ.2/ກ while the
   * other takes ມ.2/ຂ, then they trade — so every arrangement is stored and the
   * slot legitimately holds more than one lesson. Marked periods are exempt from
   * the API's clash check against each other, and only against each other.
   */
  isRotating?: boolean;
}

/**
 * Who teaches which subject, to which class, in which semester.
 *
 * The list endpoint populates teacher, subject and classroom; the two timetable
 * endpoints populate only the two references the other axis does not already
 * fix (a teacher's timetable carries subject and classroom, and vice versa).
 */
export interface TeachingAssignment extends BaseDocument {
  teacherId: Ref<Teacher>;
  subjectId: Ref<Subject>;
  classroomId: Ref<Classroom>;
  semesterId: Ref<Semester>;
  schoolYearId: Ref<SchoolYear>;
  schedule: SchedulePeriod[];
  isActive: boolean;
  notes?: string | null;
}


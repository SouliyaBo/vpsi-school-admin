/**
 * Response shapes for the modules the admin panel reads.
 *
 * The API declares request DTOs in its OpenAPI document (see
 * `src/types/api-schema.d.ts`, regenerated by `npm run gen:api`) but returns
 * serialized Mongoose documents, which the document does not describe. These
 * interfaces mirror `src/database/schemas/*.schema.ts` in the API, with two
 * transforms the serializer applies on the way out:
 *
 *   • `_id` is rendered as `id`
 *   • `Date` becomes an ISO 8601 string
 *
 * Reference fields are `Ref<T>`: an id string on list endpoints, a populated
 * object on detail endpoints. Read them with `refId()` / `refObject()`.
 */

interface BaseDocument extends WithId, Timestamped {
  deletedAt?: string | null;
}

// ── Locations ───────────────────────────────────────────────────────────────

export interface Location extends BaseDocument {
  nameLo: string;
  nameEn?: string | null;
  code?: string | null;
  type: LocationType;
  parentId?: Ref<Location>;
  /** Province → district chain, root first. */
  ancestors: string[];
  depth: number;
}

/** `GET /locations/tree` — the whole hierarchy, nested and cached server-side. */
export interface LocationTreeNode extends Location {
  children?: LocationTreeNode[];
}

